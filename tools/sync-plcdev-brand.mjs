// Keep the independent OpenPLC repo and scripts injected into native tools
// buildable on their own. Only the marked part of the banner is generated.
import {readFile,writeFile} from 'node:fs/promises';
import {brandCss,brandMark,brandName} from '../software/dsh-plcdev/src/client/brand-contract.mjs';

const banner=new URL('../software/native-preview-banner.js',import.meta.url);
const openPlc=new URL('../software/openplc-editor-zh/src/middleware/adapters/editor/plcdev-brand.generated.ts',import.meta.url);
const check=process.argv.includes('--check');
const begin='/* BEGIN GENERATED PLCDEV BRAND */';
const end='/* END GENERATED PLCDEV BRAND */';
const values={brandName,brandMark,brandCss};
const declarations=Object.entries(values).map(([name,value])=>`export const ${name} = ${JSON.stringify(value)}`).join('\n');
const native=`${begin}\nconst plcdevNativeBrand = ${JSON.stringify(values)};\n${end}\n`;
const previous=await readFile(banner,'utf8');
const generated=/\/\* BEGIN GENERATED PLCDEV BRAND \*\/[\s\S]*?\/\* END GENERATED PLCDEV BRAND \*\/\r?\n/;
for(const [file,content] of [
  [banner,generated.test(previous)?previous.replace(generated,()=>native):native+previous],
  [openPlc,'// Generated by tools/sync-plcdev-brand.mjs in PLCdev.\n'+declarations+'\n'],
]){
  if(check){
    if(await readFile(file,'utf8').catch(()=>null)!==content){
      console.error('Brand assets need regeneration: '+file.pathname);
      process.exitCode=1;
    }
  }else await writeFile(file,content);
}
